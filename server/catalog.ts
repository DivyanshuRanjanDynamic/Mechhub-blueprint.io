export function sourcingFor(item: { name: string; search: string; vendors?: SourcingLink[] }): SourcingLink[] {
  const q = encodeURIComponent(item.search);
  return [
    { vendor: "Amazon", url: `https://www.amazon.com/s?k=${q}` },
    { vendor: "AliExpress", url: `https://www.aliexpress.com/w/wholesale-${q.replace(/%20/g, "-")}.html` },
    { vendor: "DigiKey", url: `https://www.digikey.com/en/products/result?keywords=${q}` },
    ...(item.vendors ?? []),
  ];
}

export function searchLinksForName(name: string): SourcingLink[] {
  return sourcingFor({ name, search: name });
}
