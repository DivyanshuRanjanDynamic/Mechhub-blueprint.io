// Component knowledge base. Every generated blueprint is assembled from these parts, so
// pin maps, supply rails and firmware snippets stay consistent no matter who planned the design.
import type { BomCategory, BomGroup, ControllerId, SourcingLink } from "../shared/types.ts";

export type PinRole =
  | "vcc"
  | "gnd"
  | "digital"
  | "analog"
  | "pwm"
  | "sda"
  | "scl"
  | "tx"
  | "rx";

export interface PinSpec {
  name: string;
  role: PinRole;
}

export type Supply = "logic" | "5V" | "servo" | "vmotor" | "none";
export type DriverKind = "pca9685" | "motor-driver" | "stepper-driver" | "relay";

export interface CatalogItem {
  id: string;
  name: string;
  category: BomCategory;
  group: BomGroup;
  price: number;
  specs: string;
  /** which rail powers the module's VCC pin: the MCU logic rail, a 5 V rail, the servo rail or the motor rail */
  supply: Supply;
  pins: PinSpec[];
  /** device is driven from a driver's output channel rather than straight from MCU pins */
  drivenBy?: DriverKind;
  /** for drivers: how many devices one driver can run */
  channels?: number;
  driverKind?: DriverKind;
  currentMa: number;
  libs?: string[];
  /** Arduino snippets; {N} = instance suffix, {PIN:name} = allocated MCU pin */
  code?: { includes?: string[]; globals?: string; setup?: string; loop?: string };
  size: [number, number, number];
  color: string;
  search: string;
  vendors?: SourcingLink[];
  keywords: string[];
}

export interface ControllerSpec {
  id: ControllerId;
  catalog: CatalogItem;
  logic: "3V3" | "5V";
  wifi: boolean;
  digital: string[];
  pwm: string[];
  analog: string[];
  sda: string;
  scl: string;
  uart: { tx: string; rx: string } | null;
  board: string;
  pinPrefix: string;
}

